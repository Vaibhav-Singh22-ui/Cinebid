/**
 * Helper algorithm to compute the optimal Playing 11 from a squad of 12-18 players:
 * Enforces:
 * 1. Exactly 11 players (or all squad if < 11)
 * 2. Maximum 4 overseas players (0 to 4)
 * 3. At least 1 Wicketkeeper
 * 4. At least 3 Bowlers/All-Rounders
 * 5. Best player ratings and roles
 */
export function getOptimalPlaying11(squad: any[]): {
  playing11: string[];
  captainId?: string;
  viceCaptainId?: string;
} {
  if (!squad || squad.length === 0) return { playing11: [] };
  if (squad.length <= 11) {
    return {
      playing11: squad.map((p) => p.id),
      captainId: squad[0]?.id,
      viceCaptainId: squad[1]?.id,
    };
  }

  // Separate Indian vs Overseas
  const indianPlayers = squad.filter((p) => !isOverseasPlayer(p));
  const overseasPlayers = squad.filter((p) => isOverseasPlayer(p));

  // Sort by rating desc
  indianPlayers.sort((a, b) => (b.imdbRating || 9) - (a.imdbRating || 9));
  overseasPlayers.sort((a, b) => (b.imdbRating || 9) - (a.imdbRating || 9));

  // Select top max 4 overseas
  const pickedOverseas = overseasPlayers.slice(0, 4);
  const remainingNeeded = 11 - pickedOverseas.length;
  const pickedIndians = indianPlayers.slice(0, remainingNeeded);

  let selected = [...pickedOverseas, ...pickedIndians];

  // Guarantee at least 1 Wicketkeeper if available in the broader squad
  const hasKeeper = selected.some(
    (p) => p.role === "WICKETKEEPER" || p.genre?.includes("Keeper"),
  );
  if (!hasKeeper) {
    const keeperInSquad = squad.find(
      (p) => p.role === "WICKETKEEPER" || p.genre?.includes("Keeper"),
    );
    if (keeperInSquad && !selected.some((p) => p.id === keeperInSquad.id)) {
      const isKeeperOverseas = isOverseasPlayer(keeperInSquad);
      if (isKeeperOverseas) {
        // Replace lowest overseas
        if (pickedOverseas.length >= 4) {
          const lowestOverseas = pickedOverseas[pickedOverseas.length - 1];
          selected = selected.filter((p) => p.id !== lowestOverseas.id);
          selected.push(keeperInSquad);
        } else {
          // Replace lowest Indian
          const lowestIndian = selected.filter((p) => !isOverseasPlayer(p)).pop();
          if (lowestIndian) {
            selected = selected.filter((p) => p.id !== lowestIndian.id);
            selected.push(keeperInSquad);
          }
        }
      } else {
        // Replace lowest Indian
        const lowestIndian = selected.filter((p) => !isOverseasPlayer(p)).pop();
        if (lowestIndian) {
          selected = selected.filter((p) => p.id !== lowestIndian.id);
          selected.push(keeperInSquad);
        }
      }
    }
  }

  // Sort selected by role order (Batters -> Wicketkeepers -> All-Rounders -> Bowlers)
  const roleOrder: Record<string, number> = {
    BATTER: 1,
    WICKETKEEPER: 2,
    ALL_ROUNDER: 3,
    FAST_BOWLER: 4,
    SPIN_BOWLER: 5,
  };

  selected.sort((a, b) => {
    const rA = roleOrder[a.role] || 3;
    const rB = roleOrder[b.role] || 3;
    return rA - rB;
  });

  const bestPlayer = [...selected].sort((a, b) => (b.imdbRating || 9) - (a.imdbRating || 9))[0];
  const secondBest = [...selected].sort((a, b) => (b.imdbRating || 9) - (a.imdbRating || 9))[1];

  return {
    playing11: selected.map((p) => p.id),
    captainId: bestPlayer?.id,
    viceCaptainId: secondBest?.id,
  };
}

export function getRandomizedCricketSlate(
  count = 60,
  category = "ALL",
): CricketPlayerItem[] {
  let basePool = [...cricketPlayers];

  if (category && category !== "ALL") {
    const matching = basePool.filter((p) => p.category === category || p.role === category);
    if (matching.length >= count) {
      basePool = matching;
    } else if (matching.length > 0) {
      const matchIds = new Set(matching.map((p) => p.id));
      const rest = basePool.filter((p) => !matchIds.has(p.id));
      basePool = [...matching, ...rest];
    }
  }

  // Fisher-Yates shuffle
  const pool = [...basePool];
  for (let i = pool.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    const temp = pool[i]!;
    pool[i] = pool[j]!;
    pool[j] = temp;
  }

  if (count <= pool.length) {
    return pool.slice(0, count);
  }

  // If count requested exceeds base pool (e.g. 60, 85, 110, 135, 160), generate uniquely indexed players
  const extendedList: CricketPlayerItem[] = [...pool];
  let cycle = 1;
  while (extendedList.length < count) {
    for (const item of pool) {
      if (extendedList.length >= count) break;
      extendedList.push({
        ...item,
        id: `${item.id}-draft-${cycle}`,
        title: `${item.title}`,
      });
    }
    cycle++;
  }

  return extendedList.slice(0, count);
}
